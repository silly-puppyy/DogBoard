#!/usr/bin/env python3
"""Subsets the design's two variable fonts for the app (tools/fonts/subset_fonts.py).

    tools/fonts/subset_fonts.py --symbols <MaterialSymbolsRounded[FILL,GRAD,opsz,wght].ttf>
                                --codepoints <…​.codepoints> --flex <RobotoFlex[…].ttf>

Writes app/src/main/res/font/material_symbols_rounded.ttf and roboto_flex.ttf, and the icon
name table design/SymbolCodepoints.kt.
- Material Symbols Rounded (Apache-2.0): only the icons in tools/fonts/symbols.txt, as their
  codepoints (the app draws an icon by its codepoint, not by ligature); axes FILL 0-1, wght 100-700,
  opsz 20-48 kept as in the design (Kb.dc.html:11), GRAD pinned to 0.
- Roboto Flex (OFL-1.1): Latin, Latin-1/Extended-A/B, Greek, Cyrillic, punctuation, currency and
  arrows; axes wght 300-800 and opsz 8-144 kept as in the design, all other axes pinned to default.
Sources: github.com/google/material-design-icons (variablefont/), github.com/google/fonts (ofl/robotoflex).
"""
import argparse
import io
import os

from fontTools import subset
from fontTools.ttLib import TTFont
from fontTools.varLib import instancer

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "..", "..", "app", "src", "main", "res", "font")
KOTLIN = os.path.join(HERE, "..", "..", "app", "src", "main", "kotlin", "io", "github", "sillypuppyy", "dogboard", "design", "SymbolCodepoints.kt")
FLEX_UNICODES = "U+0020-007E,U+00A0-024F,U+0370-03FF,U+0400-04FF,U+1E00-1EFF,U+2000-206F,U+20A0-20CF,U+2100-214F,U+2190-21FF,U+2212,U+2248,U+2260,U+2264,U+2265,U+25CF"


def save_subset(font: TTFont, unicodes, path: str, keep_gsub: bool):
    # an instanced font must be written and read back before subsetting (lazy gvar)
    buf = io.BytesIO()
    font.save(buf)
    buf.seek(0)
    font = TTFont(buf)
    options = subset.Options()
    options.layout_features = ["*"] if keep_gsub else ["kern", "liga", "calt", "ccmp", "locl", "mark", "mkmk"]
    options.name_IDs = ["*"]
    options.notdef_outline = True
    options.glyph_names = False
    sub = subset.Subsetter(options)
    sub.populate(unicodes=unicodes)
    sub.subset(font)
    font.save(path)
    print(f"{os.path.basename(path)}: {os.path.getsize(path) // 1024} KB")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--symbols", required=True)
    ap.add_argument("--codepoints", required=True)
    ap.add_argument("--flex", required=True)
    args = ap.parse_args()
    os.makedirs(OUT, exist_ok=True)

    names = [l.strip() for l in open(os.path.join(HERE, "symbols.txt")) if l.strip() and not l.startswith("#")]
    cps = dict(l.split() for l in open(args.codepoints) if l.strip())
    missing = [n for n in names if n not in cps]
    if missing:
        raise SystemExit(f"not in Material Symbols: {missing}")
    with open(KOTLIN, "w", encoding="utf-8") as f:
        f.write("// Generated by tools/fonts/subset_fonts.py from tools/fonts/symbols.txt. Do not edit.\n")
        f.write("package io.github.sillypuppyy.dogboard.design\n\n")
        f.write("/** Material Symbols name -> codepoint, for the icons bundled in material_symbols_rounded.ttf. */\n")
        f.write("internal val SymbolCodepoints: Map<String, Int> = mapOf(\n")
        for n in names:
            f.write(f'    "{n}" to 0x{cps[n].upper()},\n')
        f.write(")\n")
    symbols = instancer.instantiateVariableFont(TTFont(args.symbols), {"GRAD": 0})
    save_subset(symbols, [int(cps[n], 16) for n in names], os.path.join(OUT, "material_symbols_rounded.ttf"), keep_gsub=False)

    flex = TTFont(args.flex)
    pinned = {a.axisTag: a.defaultValue for a in flex["fvar"].axes if a.axisTag not in ("wght", "opsz")}
    flex = instancer.instantiateVariableFont(flex, pinned)
    unicodes = []
    for part in FLEX_UNICODES.split(","):
        lo, _, hi = part[2:].partition("-")
        unicodes.extend(range(int(lo, 16), int(hi or lo, 16) + 1))
    save_subset(flex, unicodes, os.path.join(OUT, "roboto_flex.ttf"), keep_gsub=False)


if __name__ == "__main__":
    main()
