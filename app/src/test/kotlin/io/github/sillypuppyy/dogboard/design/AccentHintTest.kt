package io.github.sillypuppyy.dogboard.design

import dev.patrickgold.florisboard.ime.keyboard3.ImeLayerIds
import dev.patrickgold.florisboard.ime.keyboard3.compileLayout
import dev.patrickgold.florisboard.ime.keyboard3.touch.TouchModelOptions
import dev.patrickgold.florisboard.ime.keyboard3.touch.computeTouchModel
import io.kotest.core.spec.style.FunSpec
import io.kotest.matchers.collections.shouldBeEmpty
import io.kotest.matchers.types.shouldBeInstanceOf
import kotlinx.coroutines.coroutineScope
import org.k3lp.lib.text.K3String
import org.k3lp.lib.text.WillRequireMigrationToRichErrors
import org.k3lp.model.K3CompileResult
import java.io.File
import java.text.Normalizer

/**
 * With accent hints on, each letter's corner hint is what holding the key picks first (the popup's default): German
 * QWERTZ showed à on a while the popup picked ä (2026-11-25).
 */
@OptIn(WillRequireMigrationToRichErrors::class)
class AccentHintTest : FunSpec({
    val layouts = File("src/main/assets/extensions/org.florisboard.k3.foundation/keyboard").listFiles()!!
        .filter { it.name.endsWith(".xml") && it.readText().contains("Generated by tools/layouts/gen_layouts.py") }
        .map { "keyboard/${it.name}" }.sorted()
    fun nfc(s: String) = Normalizer.normalize(s, Normalizer.Form.NFC)

    test("every generated layout: the accent hint is the long-press default") {
        val wrong = buildList {
            for (path in layouts) {
                val result = compileLayout(path)
                result.shouldBeInstanceOf<K3CompileResult.Success>()
                val rows = LiveKb.letterRows(result.model) ?: continue
                val keyboard = coroutineScope { computeTouchModel(result.model, TouchModelOptions.Default) }.selectKeyboard(deviceWidthMm = 70)
                val popupFirst = keyboard.layers.getValue(ImeLayerIds.Base).keys.mapNotNull { k ->
                    val out = (k.attrs.output as? K3String)?.toText() ?: return@mapNotNull null
                    val first = (k.extendedPopupKeys.firstOrNull()?.data?.output as? K3String)?.toText() ?: return@mapNotNull null
                    nfc(out) to nfc(first)
                }.toMap()
                val r = KbSpec.render(KbProps(width = 375f, keyH = 216f, only = "live", letterRows = rows, hintKind = "accents"))
                for (k in r.rows.take(rows.size).flatMap { it.keys }) {
                    if (k.gap || k.kind != "char" || k.hint.isEmpty()) continue
                    val want = popupFirst[k.base] ?: continue
                    if (k.hint != want) add("$path ${k.base}: hint ${k.hint}, long-press picks $want")
                }
            }
        }
        wrong.take(10).shouldBeEmpty()
    }
})
