package io.github.sillypuppyy.dogboard.design

import dev.patrickgold.florisboard.ime.keyboard3.ImeLayerIds
import dev.patrickgold.florisboard.ime.keyboard3.compileLayout
import dev.patrickgold.florisboard.ime.keyboard3.touch.TouchModelOptions
import dev.patrickgold.florisboard.ime.keyboard3.touch.computeTouchModel
import io.kotest.core.spec.style.FunSpec
import io.kotest.matchers.collections.shouldBeEmpty
import io.kotest.matchers.shouldBe
import io.kotest.matchers.types.shouldBeInstanceOf
import kotlinx.coroutines.coroutineScope
import org.k3lp.lib.text.WillRequireMigrationToRichErrors
import org.k3lp.model.K3CompileResult
import java.io.File
import kotlin.math.abs

/**
 * For every generated layout, each letter is drawn where it is hit: the drawn key's centre (KbSpec
 * from the live layout's letter rows) within half a dp of its touch target's centre.
 */
@OptIn(WillRequireMigrationToRichErrors::class)
class DrawnEqualsTouchTest : FunSpec({
    val layouts = File("src/main/assets/extensions/org.florisboard.k3.foundation/keyboard").listFiles()!!
        .filter { it.name.endsWith(".xml") && it.readText().contains("Generated by tools/layouts/gen_layouts.py") }
        .map { "keyboard/${it.name}" }.sorted()

    for (path in layouts) test("$path: letters drawn where they are hit") {
        val result = compileLayout(path)
        result.shouldBeInstanceOf<K3CompileResult.Success>()
        val rows = LiveKb.letterRows(result.model) ?: error("no letter rows")
        val (w, h) = 375f to 216f
        val keyboard = coroutineScope { computeTouchModel(result.model, TouchModelOptions.Default) }.selectKeyboard(deviceWidthMm = 70)
        val (targets, _) = keyboard.letterTargets(ImeLayerIds.Base, w, h, 0.3)
        val r = KbSpec.render(KbProps(width = w, keyH = h, only = "live", letterRows = rows))
        val off = buildList {
            r.rows.take(rows.size).forEachIndexed { ri, row ->
                for (k in row.keys) {
                    if (k.gap || k.kind != "char" || !k.base[0].isLetter()) continue
                    val t = targets[k.base.lowercase()[0]] ?: run { add("${k.base}: no touch target"); continue }
                    val dx = k.x + k.w / 2 - t.centerX
                    val dy = r.rowTops[ri] + r.rowHs[ri] / 2 - t.centerY
                    if (abs(dx) > 0.5f || abs(dy) > 0.5f) add("%s: drawn - touch = (%.1f, %.1f) dp".format(k.base, dx, dy))
                }
            }
        }
        if (off.isNotEmpty()) {
            println("DRAWN " + r.rows[0].keys.joinToString { "%s@%.1f+%.1f".format(it.base.ifEmpty { it.kind }, it.x, it.w) })
            println("TOUCH " + rows[0].filter { it.kind == "char" }.joinToString { "%s@%.1f".format(it.base, targets[it.base[0]]?.centerX ?: -1f) })
        }
        off.shouldBeEmpty()
        // and English drawn from its layout = the built-in English rows (previews keep today's drawing)
        if (path.endsWith("qwerty-en.xml")) {
            val builtIn = KbSpec.render(KbProps(width = w, keyH = h, only = "live"))
            r.rows.take(3).map { row -> row.keys.map { "%s@%.2f+%.2f".format(it.base, it.x, it.w) } } shouldBe
                builtIn.rows.take(3).map { row -> row.keys.map { "%s@%.2f+%.2f".format(it.base, it.x, it.w) } }
        }
    }
})
