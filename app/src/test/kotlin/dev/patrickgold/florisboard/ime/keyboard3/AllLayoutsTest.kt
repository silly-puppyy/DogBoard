package dev.patrickgold.florisboard.ime.keyboard3

import dev.patrickgold.florisboard.ime.keyboard3.touch.TouchModelOptions
import dev.patrickgold.florisboard.ime.keyboard3.touch.computeTouchModel
import io.kotest.core.spec.style.FunSpec
import io.kotest.matchers.collections.shouldBeEmpty
import io.kotest.matchers.doubles.plusOrMinus
import io.kotest.matchers.shouldBe
import io.kotest.matchers.types.shouldBeInstanceOf
import kotlinx.coroutines.coroutineScope
import org.k3lp.lib.text.WillRequireMigrationToRichErrors
import org.k3lp.model.K3CompileResult
import org.k3lp.model.layer.K3LayerId
import java.io.File

/** Every layout tools/layouts/gen_layouts.py writes: compiles, full-width rows, keys exist, letters reach the decoder. */
@OptIn(WillRequireMigrationToRichErrors::class)
class AllLayoutsTest : FunSpec({
    val layouts = File("src/main/assets/extensions/org.florisboard.k3.foundation/keyboard").listFiles()!!
        .filter { it.name.endsWith(".xml") && it.readText().contains("Generated by tools/layouts/gen_layouts.py") }
        .map { "keyboard/${it.name}" }.sorted()

    test("the generated layouts are found") { (layouts.size >= 3) shouldBe true }

    for (path in layouts) {
        test("$path: compiles, rows fit, every referenced key exists") {
            val result = compileLayout(path)
            result.reports.map { it.toString() }.shouldBeEmpty()
            result.shouldBeInstanceOf<K3CompileResult.Success>()
            val model = result.model
            val layers = model.layersByForm.touch.single().layers
            for (layerId in listOf(ImeLayerIds.Base, ImeLayerIds.Shift, K3LayerId("symbol-1"), K3LayerId("symbol-2"))) {
                val layer = layers[layerId] ?: error("missing layer $layerId")
                layer.rows.forEachIndexed { i, row ->
                    val width = row.sumOf { (model.keys.byKeyId[it] ?: error("unknown key $it")).width.toDouble() }
                    // English's home row is 9 keys wide, centred by the layout engine; every other row fills 10,
                    // never more (a row over 10 units loses its last key in the touch layout)
                    (width <= 10.0) shouldBe true
                    if (!(i == 1 && width < 10)) width shouldBe (10.0 plusOrMinus 0.01)
                }
            }
            val referenced = buildSet {
                for ((_, layer) in layers) layer.rows.forEach { addAll(it) }
                for (key in model.keys.byKeyId.values) { key.longPressKeyIds?.let { addAll(it) }; key.longPressDefaultKeyId?.let { add(it) } }
            }
            referenced.filter { model.keys.byKeyId[it] == null }.map { it.toString() }.shouldBeEmpty()
        }

        test("$path: every letter of the letter rows reaches the decoder, the space bar below them") {
            val result = compileLayout(path)
            result.shouldBeInstanceOf<K3CompileResult.Success>()
            val keyboard = coroutineScope { computeTouchModel(result.model, TouchModelOptions.Default) }.selectKeyboard(deviceWidthMm = 70)
            val (keys, _) = keyboard.letterTargets(ImeLayerIds.Base, 375f, 216f, 0.3)
            val base = result.model.layersByForm.touch.single().layers.getValue(ImeLayerIds.Base)
            val drawnLetters = base.rows.take(3).flatten().mapNotNull { id ->
                (result.model.keys.byKeyId[id]?.output as? org.k3lp.lib.text.K3String)?.toText()?.takeIf { it.length == 1 && it[0].isLetter() }?.get(0)
            }
            drawnLetters.filter { it.lowercaseChar() !in keys }.shouldBeEmpty()
            val space = keys.getValue(' ')
            keys.filterKeys { it != ' ' }.values.all { space.centerY > it.centerY } shouldBe true
        }
    }

    // why the keyboard composes typed text and key labels (ImeController.emitTextTracked, TouchModel, LiveKb)
    test("the layout library returns accented letters decomposed") {
        val result = compileLayout("keyboard/qwertz-de.xml")
        result.shouldBeInstanceOf<K3CompileResult.Success>()
        val t = (result.model.keys.byKeyId[org.k3lp.model.key.K3KeyId("u00fc")]?.output as org.k3lp.lib.text.K3String).toText()
        t shouldBe "u\u0308"
        java.text.Normalizer.normalize(t, java.text.Normalizer.Form.NFC) shouldBe "ü"
    }
})
